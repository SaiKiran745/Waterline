"""Scenario grounding (contracts v1.3, judge feedback part B): tie the slider's water depth to real elevations.

Waterline does not model rainfall, drainage or flow, and says so. It ties the water level to elevations:
- Ground: USGS EPQS (3DEP, NAVD 88, feet) sampled on a ring just outside the footprint, on a grid around it and in
  front of each mapped entry point. One source only; every call cached.
- Floor: the ground at the building plus a slab allowance chosen from the CoStar door types and the doors the
  aerial survey mapped (drive-in at grade, dock-high, or a step at a pedestrian door). An assumed range.
- FEMA: the 1% annual-chance water-surface elevation from the NFHL cross-sections (layer 14, WSEL_REG) nearest the
  building, with the nearest Base Flood Elevation line (layer 16, ELEV) as a cross-check. Both carry V_DATUM.
- Each slider step d corresponds to an outside water surface at floor + d (water inside rises to the outside level).

    python -m app.loss.grounding                 # every building (EPQS is slow the first time; cached after)
    python -m app.loss.grounding building-e      # one building

Writes data/cache/buildings/<id>/grounding.json (git-ignored). GET /buildings/{id}/grounding serves it.
"""
